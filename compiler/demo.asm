; ==============================================================================
; LIM2 / sim / demo.asm — Демонстрационная программа на ассемблере LIM M2
; ==============================================================================
; Компиляция в .bin и .hex:
;     python3 limasm.py demo.asm -l
; Прямой запуск в симуляторе:
;     python3 sim.py demo.asm -i
; ==============================================================================

.org 0x0000

start:
    ; 1. Инициализация регистра флагов ($freg) и стека ($sreg) через MSP:
    MSP.ld  $freg, 0x0000           ; Глухая очистка флагового регистра
    MSP.or  $freg, 0x1000           ; Включаем бит 12 (AIP — автоинкремент PTREG)
    MSP.ld  $sreg, 0x3F00           ; Инициализация 32-битного указателя стека

    ; 2. Загрузка непосредственных констант (число без скобок -> SRC=0):
    LMR.w   $1, 100                 ; $1 = 100 (16-битное слово)
    LMR.w   $2, 50                  ; $2 = 50  (16-битное слово)

    ; 3. Регистровая арифметика и унарные 1-байтовые операции:
    ADD     $0, $1, $2              ; $0 = $1 + $2 = 150
    INC     $0                      ; $0 = 151 (1-байтовая инструкция)
    DEC     $2                      ; $2 = 49  (1-байтовая инструкция)

    ; 4. Сохранение и чтение по прямой ссылке в памяти [addr] (SRC=1 / DST=1):
    LRM.w   $0, [0x0100]            ; MEM16[0x0100] = 151
    LMR.w   $3, [0x0100]            ; $3 = MEM16[0x0100] = 151

    ; 5. Работа с 32-битным указателем $ptreg и вывод символов на экран (0x8000):
    MSP.ld  $ptreg, 0x8000          ; Направляем $ptreg на видеопамять MONITOR
    LMR.b   $4, 'O'                 ; Загружаем байт 'O' (0x4F)
    LRM.b   $4, [$ptreg]            ; Записываем в MONITOR[0] (PTREG++ за счет AIP)
    LMR.b   $4, 'K'                 ; Загружаем байт 'K' (0x4B)
    LRM.b   $4, [$ptreg]            ; Записываем в MONITOR[1] (PTREG++ за счет AIP)

    ; 6. Составной 32-битный указатель из пары регистров [$5:$6] (SRC=3):
    LMR.w   $5, 0x0000              ; Старшие биты адреса = 0x0000
    LMR.w   $6, 0x0100              ; Младшие 16 бит адреса = 0x0100
    LMR.w   $5, [$5:$6]             ; Читаем MEM16[0x000100] в $5 ($5 = 151)

    ; 7. Нативное многократное разыменование цепочки указателей через PTREG:
    ;    Подготовим цепочку указателей в ОЗУ: 0x0200 -> 0x0210 -> 0x0220 -> 0x0100
    LMR.w   $7, 0x0210
    LRM.w   $7, [0x0200]
    LMR.w   $7, 0x0220
    LRM.w   $7, [0x0210]
    LMR.w   $7, 0x0100
    LRM.w   $7, [0x0220]

    MSP.ld  $ptreg, 0x0200          ; Начальный адрес цепочки = 0x0200
    MSP.ld  $ptreg, [$ptreg]        ; 1-е разыменование: 0x0200 -> 0x0210
    MSP.ld  $ptreg, [$ptreg]        ; 2-е разыменование: 0x0210 -> 0x0220
    MSP.ld  $ptreg, [$ptreg]        ; 3-е разыменование: 0x0220 -> 0x0100
    LMR.w   $7, [$ptreg]            ; Читаем значение по финальному адресу 0x0100 ($7 = 151)

    ; 8. Маскирование флагового регистра:
    MSP.and $freg, 0x0001           ; Оставляем только флаг нуля ZF

    ; 9. Переходы по меткам (прямой JMP direct_step и косвенный JMP [ptr_cell]):
    JMP     direct_step             ; Прямой безусловный переход по метке (MOD=0)

dead_code:
    HALT                            ; Сюда управление не попадает

direct_step:
    ; Косвенный переход через указатель в памяти [ptr_cell] (MOD=3):
    JMP     [ptr_cell]

jump_target:
    ; 10. Использование $ (текущий адрес) и $$ (базовый адрес секции):
    LMR.w   $0, $$                  ; $0 = базовый адрес (0x0000)
    LMR.w   $1, $                   ; $1 = адрес текущей инструкции ($)
    LMR.w   $2, msg_len             ; длина строки через вычисление ($ - msg)

    HALT                            ; Останов процессора (1 байт)

    ; 11. Директивы данных (Little-Endian) и 3-байтный указатель dp:
ptr_cell:
    dw      jump_target             ; 2 байта (16-битный адрес цели для JMP [ptr_cell])
msg:
    db      "LIM2", 0               ; 1-байтовые символы + нуль-терминатор
msg_len = $ - msg                   ; вычисление длины на этапе ассемблирования
dp_ptr:
    dp      0x018000                ; 3-байтный указатель (24-бит, экономия 1 байта вместо 4)
dd_data:
    dd      0x12345678              ; 4-байтные сырые данные


